-- ---------------------------------------------------------------------
-- daily_puzzle: one row per calendar date (Asia/Kolkata).
-- Written by the owner via the Supabase dashboard / SQL editor.
-- Read only by the Edge Function (service role). Never by the browser.
-- ---------------------------------------------------------------------
create table if not exists public.daily_puzzle (
    sequence         integer      primary key,
    category         text         not null,
    question         text         not null,
    accepted_answers text[]       not null,
    answer_display   text         not null,
    hints            jsonb        not null default '[]'::jsonb,
    explanation      text         not null,
    active           boolean      not null default true,
    created_at       timestamptz  not null default now(),
    puzzle_date      date         not null,
    constraint daily_puzzle_puzzle_date_key unique (puzzle_date)
);


-- ---------------------------------------------------------------------
-- game_sessions: one row per browser session per day.
-- The session_id is generated by the browser (UUID) and is NOT a
-- verified identity. There is intentionally no foreign key to
-- daily_puzzle (it was dropped when puzzles moved to dated scheduling).
-- ---------------------------------------------------------------------
create table if not exists public.game_sessions (
    session_id      uuid         primary key,
    puzzle_sequence integer,
    puzzle_date     date         not null,
    attempts        integer      not null default 0,
    hints_used      integer      not null default 0,
    completed       boolean      not null default false,
    solved          boolean      not null default false,
    started_at      timestamptz  not null default now(),
    completed_at    timestamptz,
    hint_index      integer      not null default 0
);


-- ---------------------------------------------------------------------
-- Row Level Security and grants (verified 2026-10-17)
--   * RLS is enabled on both tables.
--   * There are NO policies on them.
--   * anon and authenticated hold NO privileges on them.
--   Only the Edge Function (service role) reads or writes these tables.
-- The REVOKEs matter in a fresh project, where Supabase's default
-- privileges would otherwise grant access to anon/authenticated.
-- ---------------------------------------------------------------------
alter table public.daily_puzzle  enable row level security;
alter table public.game_sessions enable row level security;

revoke all on public.daily_puzzle  from anon, authenticated;
revoke all on public.game_sessions from anon, authenticated;


